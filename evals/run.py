"""Run the full evaluation suite and write evals/RESULTS.md.

Usage:
    python -m evals.run [--agentleak-data DIR] [--out evals/RESULTS.md]

Skips a benchmark gracefully (recording why) if its optional dependency or
data is missing, so partial results are always reproducible. The generated
report contains only aggregate numbers — no benchmark payloads or PII.
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

import aire
from aire.store import EvidenceStore

_DEFAULT_OUT = Path(__file__).parent / "RESULTS.md"


def _run_agentdojo() -> dict:
    try:
        import agentdojo  # noqa: F401
    except ImportError:
        return {
            "benchmark": "AgentDojo",
            "skipped": "agentdojo not installed (pip install 'aire[eval]')",
        }
    from evals import agentdojo_eval

    corpus = agentdojo_eval.build_corpus()
    with tempfile.TemporaryDirectory() as tmp:
        store = EvidenceStore(Path(tmp) / "adojo.db")
        try:
            return agentdojo_eval.run(store, corpus).as_dict()
        finally:
            store.close()


# Tuned personal-data entity set (V1 live-validation learning): drop the
# DATE_TIME / ORGANIZATION / URL noise Presidio flags by default.
_PII_ENTITIES = [
    "PERSON",
    "EMAIL_ADDRESS",
    "PHONE_NUMBER",
    "US_SSN",
    "CREDIT_CARD",
    "IBAN_CODE",
    "IP_ADDRESS",
]


def _run_agentleak(data_dir: Path | None) -> dict:
    from evals import agentleak_eval

    try:
        from aire.detectors.pii import PIIDetector, PresidioScanner

        detector = PIIDetector(scanner=PresidioScanner(entities=_PII_ENTITIES))
    except ImportError:
        return {
            "benchmark": "AgentLeak",
            "skipped": "Presidio not installed (pip install 'aire[pii]' + spaCy model)",
        }

    channels = agentleak_eval.load_channels(data_dir)
    records = agentleak_eval.load_vault_records(data_dir)
    with tempfile.TemporaryDirectory() as tmp:
        store = EvidenceStore(Path(tmp) / "aleak.db")
        vault_store = EvidenceStore(Path(tmp) / "aleak_vault.db")
        try:
            result = agentleak_eval.run(store, channels, detector).as_dict()
            result["private_vault_pii"] = agentleak_eval.run_vault_pii(
                vault_store, records, detector
            ).as_dict()
            return result
        finally:
            store.close()
            vault_store.close()


def _run_overhead() -> dict:
    from evals import overhead

    return {**overhead.measure_append_overhead(), **overhead.measure_report_time()}


def collect(data_dir: Path | None = None) -> dict:
    return {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "aire_version": aire.__version__,
        "python": platform.python_version(),
        "platform": platform.platform(),
        "agentdojo": _run_agentdojo(),
        "agentleak": _run_agentleak(data_dir),
        "overhead": _run_overhead(),
    }


def _fmt_confusion(c: dict) -> str:
    return (
        f"TP={c['tp']} FP={c['fp']} TN={c['tn']} FN={c['fn']} · "
        f"precision={c['precision']} recall={c['recall']} F1={c['f1']} "
        f"FP-rate={c['false_positive_rate']}"
    )


def to_markdown(results: dict) -> str:
    lines = [
        "# AIRE Evaluation Results",
        "",
        "> Generated by `python -m evals.run` — every number below is computed "
        "from a named public benchmark corpus replayed through AIRE's pipeline. "
        "No figures are hand-written. Replays are offline (no LLM calls), so runs "
        "are deterministic and free to reproduce.",
        "",
        f"- Generated: {results['generated_at']}",
        f"- AIRE {results['aire_version']} · Python {results['python']} · {results['platform']}",
        "",
        "## AgentDojo — prompt-injection detection (arXiv 2406.13352)",
        "",
        "Corpus: the `important_instructions` attack rendered for every injection-task "
        "goal (positives) vs. benign injection-vector texts and user-task prompts "
        "(negatives), each replayed as a `tool.result` event.",
        "",
    ]
    ad = results["agentdojo"]
    if "skipped" in ad:
        lines += [f"**Skipped:** {ad['skipped']}", ""]
    else:
        lines += [
            f"- Positives: {ad['positives']} · Negatives: {ad['negatives']}",
            "- Detector: `prompt_injection.heuristic`",
            f"- **Result:** {_fmt_confusion(ad['confusion'])}",
            f"- Detector latency/event: {ad['detector_latency']}",
            "",
        ]

    al = results["agentleak"]
    lines += [
        "## AgentLeak — internal-channel leakage detection (arXiv 2602.11510)",
        "",
        "Internal-channel traces (inter-agent messages, shared memory) replayed as "
        "AIRE evidence events; ground truth is each channel's `pii_exposed` list. "
        "An output-only auditor sees **0%** of these internal channels.",
        "",
        "> Sample: AgentLeak ships a small set of executed internal-channel traces; "
        "the 1000-scenario corpus is scenario *definitions*, not executed traces. "
        "This measures whether AIRE surfaces the internal channels an output-only "
        "audit structurally cannot see — the benchmark's central claim.",
        "",
    ]
    if "skipped" in al:
        lines += [f"**Skipped:** {al['skipped']}", ""]
    else:
        lines += [
            f"- Data source: **{al['data_source']}** "
            + ("(synthetic CI fixture — point --agentleak-data at the dataset for real numbers)"
               if al["data_source"] == "fixture" else "(AgentLeak dataset)"),
            f"- Channels evaluated: {al['channels_total']}",
            f"- **Internal-channel PII recall:** {_fmt_confusion(al['internal_channel_recall'])}",
            f"- Output-only auditor coverage of these channels: "
            f"{al['output_only_auditor_coverage'] * 100:.0f}%",
            "",
            "Per channel kind:",
            "",
        ]
        for kind, conf in al["by_channel_kind"].items():
            lines.append(f"- `{kind}`: {_fmt_confusion(conf)}")
        lines.append("")

        vault = al.get("private_vault_pii")
        if vault:
            lines += [
                "### Private-vault PII detection (larger-N recall)",
                "",
                "Honestly scoped: AgentLeak's 100 base scenarios define private "
                "vaults of records about people — scenario *definitions*, not "
                "executed traces. This measures whether AIRE's memory PII detector "
                "surfaces each record when written to agent memory (**recall**, not "
                "leakage). Ground truth is field-name based; the detector uses the "
                "tuned personal-data entity set.",
                "",
                f"- Data source: **{vault['data_source']}** · records: {vault['records_total']}",
                f"- **Recall on identity-field records:** {vault['recall']} "
                f"({vault['identity_detected']}/{vault['identity_records']})",
                f"- Records with no explicit identity field flagged for PII in "
                f"free-text (e.g. a name in a `provider`/`references` field — a strength, "
                f"not an error): {vault['non_identity_flagged_in_free_text']}/"
                f"{vault['non_identity_records']}",
                "",
            ]

    ov = results["overhead"]
    lines += [
        "## Overhead",
        "",
        f"- Evidence-store append ({ov['events_appended']} events): "
        f"{ov['append_latency']}",
        f"- Report build ({ov['events_in_store']} events, {ov['sessions']} sessions): "
        f"{ov['report_build_ms']} ms",
        "",
        "---",
        "",
        "*Raw JSON of this run is emitted alongside for machine consumption "
        "(`python -m evals.run --json`).*",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run AIRE evaluation suite")
    parser.add_argument(
        "--agentleak-data",
        type=Path,
        default=None,
        help="Path to AgentLeak agentleak_data/datasets directory",
    )
    parser.add_argument("--out", type=Path, default=_DEFAULT_OUT)
    parser.add_argument("--json", action="store_true", help="Print raw JSON to stdout")
    args = parser.parse_args(argv)

    results = collect(args.agentleak_data)
    if args.json:
        print(json.dumps(results, indent=2))
        return 0

    args.out.write_text(to_markdown(results))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
